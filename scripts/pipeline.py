def publish(root, files):
    """Validate before calling. Roll back all replaced files on Python exceptions.

    Per-file replacement is atomic; concurrent writers and power-loss recovery
    require an external transaction boundary (e.g. a reviewed Git commit).
    """
    files = {name: body for name, body in files.items()
             if not (root / name).exists() or (root / name).read_bytes() != body}
    previous = {name: (root / name).read_bytes() if (root / name).exists() else None for name in files}
    replaced = []
    with tempfile.TemporaryDirectory(prefix='.risposte-build-', dir=root) as temp:
        staging = Path(temp)
        for name, body in files.items():
            path = staging / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(body)
        try:
            for name in files:
                target = root / name
                target.parent.mkdir(parents=True, exist_ok=True)
                os.replace(staging / name, target)
                replaced.append(name)
        except BaseException:
            for name in reversed(replaced):
                target = root / name
                if previous[name] is None:
                    target.unlink(missing_ok=True)
                else:
                    target.write_bytes(previous[name])
            raise


def check(root):
    files, manifest = derive(root)
    stale = [name for name, body in files.items() if not (root / name).exists() or (root / name).read_bytes() != body]
    if stale:
        raise ValueError('Generated files differ from canonical inputs; run build:\n' + '\n'.join(stale))
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=['build', 'check'])
    args = parser.parse_args()
    try:
        if args.command == 'build':
            files, manifest = derive(ROOT)
            publish(ROOT, files)
        else:
            manifest = check(ROOT)
        print(f"OK: {manifest['documentary_units']} units, {manifest['gap_rows']} reference gap ranges; "
              f"reference count {manifest['reference_coverage']['ratio']}; coverage status {manifest['coverage_status']}")
        for issue in manifest['editorial_issues']:
            print('EDITORIAL:', issue['detail'])
    except (ValueError, KeyError, OSError) as exc:
        parser.exit(1, str(exc) + '\n')


if __name__ == '__main__':
    main()

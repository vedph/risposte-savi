def json_bytes(obj):
    return (json.dumps(obj, ensure_ascii=False, indent=2, allow_nan=False) + '\n').encode('utf-8')


def csv_bytes(rows, columns):
    out = io.StringIO(newline='')
    writer = csv.DictWriter(out, fieldnames=columns, extrasaction='ignore', lineterminator='\n')
    writer.writeheader()
    writer.writerows(rows)
    return out.getvalue().encode()


def read_csv(path):
    with path.open(encoding='utf-8-sig', newline='') as stream:
        return list(csv.DictReader(stream))


def js_bytes(name, value):
    return ('// Generated by scripts/pipeline.py; do not edit.\nwindow.' + name + '=' +
            json.dumps(value, ensure_ascii=False).replace('</', '<\\/') + ';\n').encode()


def normalize_hyp(rows):
    result = []
    for row in rows:
        r = {k: str(row[k]) if row.get(k) is not None else '' for k in HYP_COLS}
        r['feature'] = row.get('feature') or row.get('field', '')
        r['rule'] = row.get('rule') or row.get('rule_id', '')
        result.append(r)
    return result


